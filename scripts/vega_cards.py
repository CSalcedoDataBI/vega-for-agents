"""Render the Vega expression and event-stream reference cards from their catalogues.

Every card under reference/vega/ is generated here from exports/vega-v6.*.catalog.json and nothing
else: names, signatures, categories and descriptions all come from the catalogue, which comes from
the pinned Vega source. `extract_catalog.py` writes the cards and `--check` fails if one differs.
"""

from __future__ import annotations

import json

DOCS = "https://vega.github.io/vega/docs/"
HEADER = ("> Generated by `scripts/extract_catalog.py` from the Vega {version} source and docs "
          "(`{commit}`, BSD-3-Clause). Do not edit by hand.")


def _front(fields: dict) -> str:
    return "---\n" + "".join(f"{k}: {v}\n" for k, v in fields.items()) + "---\n"


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def expression_cards(cat: dict) -> dict[str, str]:
    meta = cat["meta"]
    head = HEADER.format(version=meta["vegaVersion"], commit=meta["commit"][:7])
    by_name = {f["name"]: f for f in cat["functions"]}
    cards: dict[str, str] = {}

    for c in cat["categories"]:
        out = [_front({
            "language": "vega",
            "vegaVersion": meta["vegaVersion"],
            "category": c["id"],
            "title": c["title"],
            "functions": len(c["functions"]),
            "source": f"docs/docs/expressions.md@{meta['commit'][:7]}",
        }), f"# {c['title']} — Vega expressions\n", head, ""]
        if c["intro"]:
            out += [c["intro"], ""]
        out += ["| Function | Signature | Since |", "|---|---|---|"]
        groups: list[tuple[str, list[str]]] = []
        for name in c["functions"]:
            f = by_name[name]
            for d in f["docs"]:
                if d["category"] != c["id"]:
                    continue
                out.append(f"| `{name}` | `{_cell(', '.join(d['signatures']))}` | "
                           f"{f['since'] or ''} |")
                for anchor, names in groups:
                    if anchor == d["anchor"]:
                        if name not in names:
                            names.append(name)
                        break
                else:
                    groups.append((d["anchor"], [name]))
        out.append("")
        for anchor, names in groups:
            first = by_name[names[0]]
            doc = next(d for d in first["docs"] if d["category"] == c["id"] and d["anchor"] == anchor)
            sigs = [s for n in names for d in by_name[n]["docs"]
                    if d["category"] == c["id"] and d["anchor"] == anchor for s in d["signatures"]]
            out += [f"## {' · '.join(f'`{n}`' for n in names)}", ""]
            out += [f"`{s}`  " for s in sigs]
            out += ["", doc["description"], "",
                    f"[Vega docs]({DOCS}expressions/#{anchor}) · defined in "
                    f"`{first['definedIn']}`", ""]
        cards[f"reference/vega/expressions/{c['id']}.md"] = "\n".join(out).rstrip() + "\n"

    # The index: categories, constants, bound variables, every function, the undocumented ones.
    documented = [f for f in cat["functions"] if f["documented"]]
    hidden = [f for f in cat["functions"] if not f["documented"]]
    titles = {c["id"]: c["title"] for c in cat["categories"]}
    out = [_front({
        "language": "vega",
        "vegaVersion": meta["vegaVersion"],
        "functions": len(cat["functions"]),
        "documented": len(documented),
        "source": f"vega/vega@{meta['commit'][:7]}",
    }), "# Vega expression functions\n", head, "",
        f"Every function the Vega {meta['vegaVersion']} expression language accepts: "
        f"**{len(cat['functions'])}** registered in the code, **{len(documented)}** of them "
        f"documented, in **{len(cat['categories'])}** categories. Vega-Lite expressions "
        "(`calculate`, `filter`, `expr`, `test`) compile to Vega expressions and use this same set.",
        "", "A call to any name that is not in this list fails to parse in Vega.", "",
        "## Categories", "", "| Category | Functions |", "|---|---|"]
    for c in cat["categories"]:
        out.append(f"| [{c['title']}]({c['id']}.md) | {len(c['functions'])} |")
    out += ["", "## Bound variables", "",
            "Names the expression code generator binds besides signals: "
            + ", ".join(f"`{v}`" for v in cat["boundVariables"]) + ". Any in-scope signal is also "
            "readable by name.", "", "## Constants", "", "| Constant | Value |", "|---|---|"]
    out += [f"| `{k['name']}` | `{k['value']}` |" for k in cat["constants"]]
    out += ["", "## All documented functions", "", "| Function | Category | Signature |",
            "|---|---|---|"]
    for f in documented:
        cats = ", ".join(f"[{titles[i]}]({i}.md)" for i in f["categories"])
        out.append(f"| `{f['name']}` | {cats} | `{_cell(' / '.join(f['signatures']))}` |")
    out += ["", "## Registered but not documented", "",
            "The code accepts these names, but the Vega docs do not list them: internal helpers "
            "the mark encoders call, and the selection plumbing Vega-Lite compiles to. They are "
            "here so an agent can recognise them in compiled output, not to be written by hand.",
            "", "| Name | Kind | Defined in |", "|---|---|---|"]
    out += [f"| `{f['name']}` | {f['kind']} | `{f['definedIn']}` |" for f in hidden]
    cards["reference/vega/expressions/README.md"] = "\n".join(out).rstrip() + "\n"
    return cards


def event_stream_card(cat: dict) -> dict[str, str]:
    meta = cat["meta"]
    head = HEADER.format(version=meta["vegaVersion"], commit=meta["commit"][:7])
    special = {s["type"]: s for s in cat["specialEventTypes"]}
    out = [_front({
        "language": "vega",
        "vegaVersion": meta["vegaVersion"],
        "source": f"docs/docs/event-streams.md@{meta['commit'][:7]}",
    }), "# Event streams — Vega\n", head, "",
        "An event stream is what a signal handler listens to (`\"on\": [{\"events\": …}]`). It is "
        "written as an object, as a selector string, or as a signal or scale reference. The JSON "
        "Schema types the selector as a free string; this card is the grammar Vega actually parses.",
        "", "## Selector string", "", f"General form: `{cat['generalForm']}`", "",
        "| Piece | Syntax |", "|---|---|"]
    labels = {
        "merge": "merge several streams", "sourceSeparator": "source before the type",
        "markname": "mark name prefix", "filter": "filter (one or more, combined with and)",
        "between": "between two streams", "timing": "throttle and debounce, in ms",
        "consume": "consume (`preventDefault`), after the type",
    }
    out += [f"| {labels[k]} | `{_cell(v)}` |" for k, v in cat["syntax"].items()]
    out += ["", "## Sources", "",
            f"Default source: `{cat['defaultSource']}` (`scope` inside a nested group). "
            "Named sources: " + ", ".join(f"`{s}`" for s in cat["namedSources"]) + ". A mark type "
            "or `@markname` before the colon restricts the stream to those marks. Anything else "
            "before the colon is read as a CSS selector for DOM elements outside the view.", "",
            "Mark types the parser recognises: " + ", ".join(f"`{m}`" for m in cat["markTypes"])
            + ".", "", "## Event types", "",
            "On marks, the view and the scope: " + ", ".join(f"`{t}`" for t in cat["markEventTypes"])
            + ".", ""]
    if "timer" in special:
        out.append(f"- `timer`: {special['timer']['note']}.")
    for s in cat["specialEventTypes"]:
        if s.get("source"):
            out.append(f"- `{s['type']}` on the `{s['source']}` source (since Vega {s['since']}).")
    out += ["", "Other DOM sources (`window`, a CSS selector) take any event type the browser "
            "fires there.", "", "## Event stream object", "",
            "| Property | Type | Required | Description |", "|---|---|---|---|"]
    for p in cat["objectProperties"]:
        out.append(f"| `{p['name']}` | {_cell(p['type'])} | {'yes' if p['required'] else ''} | "
                   f"{_cell(p['description'])} |")
    out += ["", "`stream` (a derived stream) and `merge` are each required only in their own "
            "form of the object.", "", "## References", ""]
    out += [f"- {r['name']} reference: `{{\"{r['key']}\": \"…\"}}` fires when that "
            f"{r['key']} changes." for r in cat["references"]]
    out += ["", "## Examples, as the parser reads them", ""]
    for ex in cat["examples"]:
        note = f" — {ex['comment']}" if ex["comment"] else ""
        out += [f"`{ex['selector']}`{note}", "", "```json",
                json.dumps(ex["parsed"], ensure_ascii=False), "```", ""]
    out.append(f"[Vega docs]({DOCS}event-streams/)")
    return {"reference/vega/event-streams.md": "\n".join(out).rstrip() + "\n"}
